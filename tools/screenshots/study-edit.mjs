// Planredigering: node study-edit.mjs <out-dir> [theme]
import { chromium } from 'playwright';
import { join, dirname } from 'path';
import { mkdirSync, existsSync } from 'fs';
import { fileURLToPath } from 'url';
const AUTH = join(dirname(fileURLToPath(import.meta.url)), 'out', '.auth.json');
const [out, theme = 'light'] = process.argv.slice(2);
const BASE = process.env.BASE_URL || 'http://localhost:4301';
mkdirSync(out, { recursive: true });
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, storageState: existsSync(AUTH) ? AUTH : undefined });
await ctx.addInitScript((t) => {
  localStorage.setItem('potteryTrackerSettings', JSON.stringify({ theme: t }));
  localStorage.setItem('pwaInstallDismissed', '1');
}, theme);
const page = await ctx.newPage();
page.on('pageerror', (e) => console.error('PAGEERROR', e.message));
page.on('console', (m) => { if (m.type() === 'error') console.error('CONSOLE', m.text()); });
const shot = async (n, full = false) => { await page.waitForTimeout(700); await page.screenshot({ path: join(out, `${n}.png`), fullPage: full }); console.log('shot', n); };
const click = (loc) => loc.evaluate((el) => el.click());
await page.goto(`${BASE}/studie`, { waitUntil: 'networkidle' });
await shot('e0-idag-banner');
await page.goto(`${BASE}/studie/plan`, { waitUntil: 'networkidle' });
await shot('e1-banner');
await click(page.getByRole('button', { name: 'Redigera', exact: true }));
await page.waitForTimeout(400);
await click(page.locator('.chapter-edit').first());
await page.waitForTimeout(600);
await shot('e2-block');
await page.locator('[aria-label="Drejning"]').first().fill('Cylindrar: 8 à 600 g. Ändrad i testet.');
await click(page.locator('button[form="block-edit"]'));
await page.waitForTimeout(900);
await shot('e2b-efter-spara');
console.log('ERR', await page.locator('.edit-errors').innerText().catch(() => 'inga'));
await click(page.getByRole('button', { name: /Nytt kort/ }));
await page.waitForTimeout(500);
await page.locator('#card-edit input').first().fill('Tunn botten');
await page.locator('#card-edit textarea').first().fill('Mät bottnen med en nål på alla i serien.');
await shot('e3-kort');
await click(page.locator('button[form="card-edit"]'));
await page.waitForTimeout(900);
// Ogiltig ändring: överlappande veckor
await click(page.locator('.chapter-edit').first());
await page.waitForTimeout(500);
await page.locator('#block-edit input[inputmode="numeric"]').first().fill('3');
await click(page.locator('button[form="block-edit"]'));
await page.waitForTimeout(900);
await shot('e4-fel');
await page.keyboard.press('Escape');
await page.waitForTimeout(400);
await click(page.getByRole('tab', { name: 'Versioner' }));
await shot('e5-versioner', true);
await click(page.locator('.rev-btn').first());
await page.waitForTimeout(400);
await click(page.getByRole('button', { name: 'Återställ', exact: true }).last());
await page.waitForTimeout(900);
await shot('e6-aterstalld', true);
console.log('overflow', await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth));
await browser.close();
