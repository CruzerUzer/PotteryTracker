// Glasyrtester: node study-glaze.mjs <out-dir> <bild> [theme]
import { chromium } from 'playwright';
import { join, dirname } from 'path';
import { mkdirSync, existsSync } from 'fs';
import { fileURLToPath } from 'url';
const AUTH = join(dirname(fileURLToPath(import.meta.url)), 'out', '.auth.json');
const [out, photo, theme = 'light'] = process.argv.slice(2);
const BASE = process.env.BASE_URL || 'http://localhost:4301';
mkdirSync(out, { recursive: true });
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, storageState: existsSync(AUTH) ? AUTH : undefined });
await ctx.addInitScript((t) => {
  localStorage.setItem('potteryTrackerSettings', JSON.stringify({ theme: t }));
  localStorage.setItem('pwaInstallDismissed', '1');
}, theme);
const page = await ctx.newPage();
page.on('pageerror', (e) => console.error('PAGEERROR', e.message));
page.on('console', (m) => { if (m.type() === 'error') console.error('CONSOLE', m.text()); });
const shot = async (n, full = false) => { await page.waitForTimeout(700); await page.screenshot({ path: join(out, `${n}.png`), fullPage: full }); console.log('shot', n); };
const click = (loc) => loc.evaluate((el) => el.click());
await page.goto(`${BASE}/studie/glasyr`, { waitUntil: 'networkidle' });
await click(page.getByRole('tab', { name: 'Recept' }));
await click(page.getByRole('button', { name: /Nytt recept/ }));
await page.waitForTimeout(500);
await page.locator('#recipe-form input').first().fill('Glasklart');
const rows = async () => page.locator('.recipe-row');
await page.locator('.recipe-row input').nth(0).fill('Fältspat');
await page.locator('.recipe-row input').nth(1).fill('30');
await click(page.getByRole('button', { name: /Lägg till ingrediens/ }));
await page.locator('.recipe-row input').nth(2).fill('Kaolin');
await page.locator('.recipe-row input').nth(3).fill('20');
await shot('g1-recept');
await click(page.locator('button[form="recipe-form"]'));
await page.waitForTimeout(800);
await click(page.getByRole('tab', { name: 'Provplattor' }));
await click(page.getByRole('button', { name: /Ny provplatta/ }));
await page.waitForTimeout(800);
await page.locator('#glaze-test-form select').nth(2).selectOption({ label: 'Glasklart (kon )' }).catch(async () => {
  await page.locator('#glaze-test-form select').nth(2).selectOption({ index: 1 });
});
await page.locator('#glaze-test-form input[inputmode="decimal"]').fill('3');
await page.locator('#glaze-test-form textarea').fill('Blank, lite rinnig på kanten.');
await page.locator('#glaze-test-form select').last().selectOption({ index: 1 });
await page.setInputFiles('#glaze-test-form input[type="file"]', photo);
await page.waitForSelector('#glaze-test-form .logbook-photo img');
await shot('g2-provplatta');
await click(page.locator('button[form="glaze-test-form"]'));
await page.waitForTimeout(900);
await shot('g3-lista');
console.log('overflow', await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth));
await browser.close();
