// Timertest med fejkad klocka: node study-timer.mjs <out-dir> [theme]
import { chromium } from 'playwright';
import { join, dirname } from 'path';
import { mkdirSync, existsSync } from 'fs';
import { fileURLToPath } from 'url';
const AUTH = join(dirname(fileURLToPath(import.meta.url)), 'out', '.auth.json');
const [out, theme = 'light'] = process.argv.slice(2);
const BASE = process.env.BASE_URL || 'http://localhost:4301';
mkdirSync(out, { recursive: true });
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, storageState: existsSync(AUTH) ? AUTH : undefined });
await ctx.addInitScript((t) => {
  localStorage.setItem('potteryTrackerSettings', JSON.stringify({ theme: t }));
  localStorage.setItem('pwaInstallDismissed', '1');
}, theme);
const page = await ctx.newPage();
page.on('pageerror', (e) => console.error('PAGEERROR', e.message));
page.on('console', (m) => { if (m.type() === 'error') console.error('CONSOLE', m.text()); });
const d = new Date(); d.setHours(9, 47, 0, 0);
await page.clock.install({ time: d });
await page.goto(`${BASE}/studie`, { waitUntil: 'networkidle' });
const shot = async (n, full = false) => { await page.waitForTimeout(600); await page.screenshot({ path: join(out, `${n}.png`), fullPage: full }); console.log('shot', n); };
await page.getByRole('button', { name: /Förbered passet|Fortsätt/ }).first().click();
await page.waitForURL(/\/studie\/pass\//);
await page.waitForTimeout(800);
await page.getByRole('radio', { name: 'Ange starttid' }).click();
await page.fill('input[type="time"]', '10:00');
await shot('t1-start', true);
await page.getByRole('button', { name: 'Starta passet' }).click();
await page.waitForTimeout(800);
await shot('t2-0947');
console.log('seg 09:47', await page.locator('.timer-seg-name').innerText());
await page.clock.fastForward('28:00');
await page.waitForTimeout(1500);
console.log('seg 10:15', await page.locator('.timer-seg-name').innerText());
await shot('t3-1015');
await page.reload({ waitUntil: 'networkidle' });
await page.waitForTimeout(1200);
console.log('seg reload', await page.locator('.timer-seg-name').innerText());
await page.clock.fastForward('01:12:00');
await page.waitForTimeout(1500);
await shot('t4-finish', true);
console.log('seg finish', await page.locator('.timer-seg-name').innerText());
await page.getByRole('button', { name: /Nästa segment/ }).click();
await page.waitForTimeout(1500);
console.log('after next', await page.locator('.timer-seg-name').innerText());
await page.clock.fastForward('02:00:00');
await page.waitForTimeout(1500);
await shot('t5-over');
await page.getByRole('button', { name: 'Avsluta passet' }).click();
await page.waitForTimeout(1200);
await shot('t6-ended');
await browser.close();
